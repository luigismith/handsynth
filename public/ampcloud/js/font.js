const parse = (src) =>
  Object.fromEntries(Object.entries(src).map(([k, v]) => [k, v.split(' ').map((row) => [...row].map(Number))]));

export const BIG = { glyphs: parse(BIG_SRC), w: 5, h: 7, advance: 6 };
export const SMALL = { glyphs: parse(SMALL_SRC), w: 3, h: 5, advance: 4 };

/** Uppercase + strip accents so "Città" renders as "CITTA". */
export const normalize = (text) =>
  String(text)
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toUpperCase();

export function textWidth(text, font = BIG) {
  return normalize(text).length * font.advance;
}

/** Draw text into a 2D context at integer pixel coordinates. */
export function drawText(ctx, text, x, y, color, font = BIG) {
  ctx.fillStyle = color;
  let cx = Math.round(x);
  const fallback = font.glyphs['?'] || font.glyphs[' '];
  for (const ch of normalize(text)) {
    const g = font.glyphs[ch] || fallback;
    for (let r = 0; r < g.length; r++) {
      const row = g[r];
      for (let c = 0; c < row.length; c++) if (row[c]) ctx.fillRect(cx + c, y + r, 1, 1);
    }
    cx += font.advance;
  }
  return cx;
}

// Seven-segment digits, 9x13, for the big time display.
const SEGMENTS = {
  a: [1, 0, 7, 2],
  b: [7, 1, 2, 6],
  c: [7, 6, 2, 6],
  d: [1, 11, 7, 2],
  e: [0, 6, 2, 6],
  f: [0, 1, 2, 6],
  g: [1, 5.5, 7, 2],
};
const DIGIT_SEGS = {
  '0': 'abcdef',
  '1': 'bc',
  '2': 'abged',
  '3': 'abgcd',
  '4': 'fgbc',
  '5': 'afgcd',
  '6': 'afgedc',
  '7': 'abc',
  '8': 'abcdefg',
  '9': 'abcdfg',
  '-': 'g',
  ' ': '',
};

export function drawDigit(ctx, ch, x, y, on, off) {
  const segs = DIGIT_SEGS[ch] ?? '';
  for (const [name, [sx, sy, w, h]] of Object.entries(SEGMENTS)) {
    const lit = segs.includes(name);
    if (!lit && !off) continue;
    ctx.fillStyle = lit ? on : off;
    // trim the segment ends by a pixel so neighbours don't merge: reads as LCD
    const yy = Math.floor(y + sy);
    if (w > h) ctx.fillRect(x + sx + 1, yy, w - 2, h);
    else ctx.fillRect(x + sx, yy + 1, w, h - 2);
  }
}
